# Six independent inner decoration inserts, all modeled on their own base plane.
w=param('inner_white_key_width',24.0)
h=param('inner_white_key_height',9.0)
t=param('inner_white_key_thickness',0.7)
r=param('inner_white_key_corner_radius',0.8)
groove_w=param('inner_white_key_groove_width',0.5)
groove_d=param('inner_white_key_groove_depth',0.25)
body=extrude(RectangleRounded(w,h,r),amount=t)
body-=Pos(0,0,t-groove_d)*extrude(Rectangle(groove_w,h+0.2),amount=groove_d+0.1)
assert len(body.solids())==1 and t-groove_d>=0.4
body.color=Color(0.97,0.97,0.95)
publish('inner_white_key',body,'13 白色双格嵌件',material='petg')
w=param('inner_bar_left_length',10.0)
h=param('inner_bar_left_width',1.6)
t=param('inner_bar_left_thickness',0.7)
body=extrude(SlotOverall(w,h),amount=t)
body.color=Color(0.012,0.03,0.025)
publish('inner_bar_left',body,'14 左圆角短条',material='petg')
w=param('inner_bar_right_length',10.0)
h=param('inner_bar_right_width',1.6)
t=param('inner_bar_right_thickness',0.7)
body=extrude(SlotOverall(w,h),amount=t)
body.color=Color(0.012,0.03,0.025)
publish('inner_bar_right',body,'15 右圆角短条',material='petg')
d=param('inner_yellow_disk_diameter',7.0)
t=param('inner_yellow_disk_thickness',0.7)
r=param('inner_yellow_disk_edge_radius',0.15)
body=Cylinder(d/2,t,align=(Align.CENTER,Align.CENTER,Align.MIN))
body=fillet(body.edges().filter_by(GeomType.CIRCLE),radius=r)
body.color=Color(1.0,0.8,0.015)
publish('inner_yellow_disk',body,'16 黄色小圆饼',material='petg')
w=param('inner_lower_left_width',24)
h=param('inner_lower_left_height',10)
t=param('inner_lower_left_thickness',0.7)
r=param('inner_lower_left_corner_radius',0.8)
body=extrude(RectangleRounded(w,h,r),amount=t)
body.color=Color(0.008,0.025,0.02)
publish('inner_lower_left',body,'17 下方左黑块',material='petg')
w=param('inner_lower_right_width',24)
h=param('inner_lower_right_height',10)
t=param('inner_lower_right_thickness',0.7)
r=param('inner_lower_right_corner_radius',0.8)
body=extrude(RectangleRounded(w,h,r),amount=t)
body.color=Color(0.008,0.025,0.02)
publish('inner_lower_right',body,'18 下方右黑块',material='petg')
